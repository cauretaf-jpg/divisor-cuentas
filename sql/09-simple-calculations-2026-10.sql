-- Cuenta Clara 2.0: almacenamiento separado para la calculadora simple.
-- No altera app_states ni cuentas compartidas de la versión avanzada.
CREATE TABLE IF NOT EXISTS public.simple_calculations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  client_id text NOT NULL CHECK (length(client_id) BETWEEN 1 AND 100),
  payload jsonb NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, client_id)
);
CREATE INDEX IF NOT EXISTS simple_calculations_user_updated_idx
  ON public.simple_calculations (user_id, updated_at DESC);
ALTER TABLE public.simple_calculations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.simple_calculations FROM PUBLIC, anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.simple_calculations TO authenticated;
-- Postgres identidad secuencial; conceder acceso de inserción al rol autenticado.
GRANT USAGE, SELECT ON SEQUENCE public.simple_calculations_id_seq TO authenticated;
CREATE POLICY "simple_select_own" ON public.simple_calculations
 FOR SELECT TO authenticated USING (user_id = (select auth.uid()));
CREATE POLICY "simple_insert_own" ON public.simple_calculations
 FOR INSERT TO authenticated WITH CHECK (user_id = (select auth.uid()));
CREATE POLICY "simple_update_own" ON public.simple_calculations
 FOR UPDATE TO authenticated USING (user_id = (select auth.uid()))
 WITH CHECK (user_id = (select auth.uid()));
CREATE POLICY "simple_delete_own" ON public.simple_calculations
 FOR DELETE TO authenticated USING (user_id = (select auth.uid()));
